  let language = 'ru';
  try { if (localStorage.getItem('qaras.language') === 'en') language = 'en'; } catch (_) { /* Storage can be unavailable in private mode. */ }
  function message(source, ...values) {
    if (source && typeof source === 'object' && !Array.isArray(source)) return source;
    const raw = Array.isArray(source) ? source.reduce((text, part, index) => text + (index ? `{${index - 1}}` : '') + part, '') : String(source ?? '');
    return { key: raw.trim(), values, before: raw.match(/^\s*/)[0], after: raw.trim() ? raw.match(/\s*$/)[0] : '' };
  }
  function t(source, ...values) {
    const item = message(source, ...values);
    const template = language === 'en' ? english[item.key] ?? item.key : item.key;
    return (item.before || '') + template.replace(/\{(\d+)\}/g, (_, index) => String(item.values?.[Number(index)] ?? '')) + (item.after || '');
  }
  function setLanguage(next) {
    if (!['ru', 'en'].includes(next)) return;
    language = next;
    try { localStorage.setItem('qaras.language', next); } catch (_) { /* The selected language still works in this tab. */ }
  }
  function translateDocument() {
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.getAttribute('data-i18n')); });
    for (const attribute of ['aria-label', 'title', 'alt']) {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`))));
    }
  }
  function ageEstimate(value) {
    const age = Math.round(value);
    const form = new Intl.PluralRules(language).select(age);
    const key = form === 'one' ? '≈ {0} год' : language === 'ru' && form === 'few' ? '≈ {0} года' : '≈ {0} лет';
    return t(message(key, age));
  }
